import { test, expect } from "@playwright/test";
import { writeFileSync } from "node:fs";
test.use({viewport:{width:844,height:390},hasTouch:true,isMobile:true});
test.beforeEach(({},info)=>test.skip(info.config.metadata.lessonHarness!==true,"Dedicated diagnostic source harness only."));
test("landscape pointer trim, coaching pause and saved resume",async({page},info)=>{
 const read=async()=>JSON.parse((await page.locator('#telemetry').textContent())!);
 const trace:unknown[]=[];
 await page.goto('/tests/browser/lesson-harness.html');
 await page.getByRole('button',{name:'Catch the wind',exact:true}).click();
 await page.getByRole('button',{name:'Free sail',exact:true}).click();
 await page.keyboard.down('KeyS');await page.waitForTimeout(1600);await page.keyboard.up('KeyS');
 expect((await read()).earned).toEqual([]);expect((await read()).stage).toBe('free-sail');
 await page.reload();expect((await read()).stage).toBe('free-sail');
 await page.getByRole('button',{name:'Continue lesson',exact:true}).click();
 expect((await read()).progress).toBe(0);
 trace.push({event:'resume-unearned',snapshot:await read()});
 const button=page.locator('[data-control="sheet"]');const box=(await button.boundingBox())!;
 await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();
 await expect.poll(async()=>(await read()).sheet).toBeLessThan(.59);await page.mouse.up();
 await expect(page.locator('body')).toHaveAttribute('data-stage','stall');
 trace.push({event:'pointer-trim-earned',snapshot:await read()});
 await page.getByRole('button',{name:'Pause',exact:true}).click();
 const time=(await read()).simulationTime;await page.waitForTimeout(500);
 expect((await read()).simulationTime).toBe(time);
 await page.screenshot({path:info.outputPath('landscape-pointer-pause.png')});
 await page.reload();const saved=await read();expect(saved.stage).toBe('stall');expect(saved.earned).toEqual([0]);expect(saved.progress).toBe(0);
 trace.push({event:'reload',snapshot:saved});
 writeFileSync(info.outputPath('pointer-trace.json'),JSON.stringify(trace,null,2));
});
